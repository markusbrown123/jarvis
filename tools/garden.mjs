// Where the house's own garden plants stand, read from lair.glb's joined
// 'plants' mesh (tools/blender/lair.py: shrubs round the terrace and the
// back, a few trees of a trunk and three crowns), so trees.ts can plant game
// foliage in the same places.
//
//   node tools/garden.mjs   → src/station/garden.ts

import fs from 'node:fs'

const b = fs.readFileSync(new URL('../public/station/lair.glb', import.meta.url))
const len = b.readUInt32LE(12)
const j = JSON.parse(b.subarray(20, 20 + len))
const bin = b.subarray(20 + len + 8)
const node = j.nodes.find((n) => n.name === 'plants')
const prim = j.meshes[node.mesh].primitives[0]
const read = (i) => {
  const a = j.accessors[i]
  const v = j.bufferViews[a.bufferView]
  const C = { 5126: Float32Array, 5125: Uint32Array, 5123: Uint16Array }[a.componentType]
  const n = a.count * { SCALAR: 1, VEC2: 2, VEC3: 3 }[a.type]
  const off = bin.byteOffset + (v.byteOffset || 0) + (a.byteOffset || 0)
  return new C(bin.buffer.slice(off, off + n * C.BYTES_PER_ELEMENT))
}
const P = read(prim.attributes.POSITION)
const I = read(prim.indices)
const n = P.length / 3

// Each plant part is one connected piece once coincident vertices are welded.
const parent = Int32Array.from({ length: n }, (_, i) => i)
const find = (x) => {
  while (parent[x] !== x) x = parent[x] = parent[parent[x]]
  return x
}
const weld = new Map()
for (let i = 0; i < n; i++) {
  const k = `${P[i * 3].toFixed(3)},${P[i * 3 + 1].toFixed(3)},${P[i * 3 + 2].toFixed(3)}`
  if (weld.has(k)) parent[find(i)] = find(weld.get(k))
  else weld.set(k, i)
}
for (let t = 0; t < I.length; t += 3) {
  const a = find(I[t])
  parent[find(I[t + 1])] = a
  parent[find(I[t + 2])] = a
}
const parts = new Map()
for (let i = 0; i < n; i++) {
  const r = find(i)
  const p = parts.get(r) ?? { min: [Infinity, Infinity, Infinity], max: [-Infinity, -Infinity, -Infinity] }
  for (let k = 0; k < 3; k++) {
    p.min[k] = Math.min(p.min[k], P[i * 3 + k])
    p.max[k] = Math.max(p.max[k], P[i * 3 + k])
  }
  parts.set(r, p)
}

// Trunks are thin and tall; shrubs sit on the ground; crowns (up in the air) go with their trunk.
const r2 = (v) => Math.round(v * 100) / 100
const trees = []
const shrubs = []
for (const p of parts.values()) {
  const w = Math.max(p.max[0] - p.min[0], p.max[2] - p.min[2])
  const h = p.max[1] - p.min[1]
  const x = (p.min[0] + p.max[0]) / 2
  const z = (p.min[2] + p.max[2]) / 2
  if (w < 0.6 && h > 2.5) trees.push([r2(x), r2(z), r2(p.max[1] + 1.4)])
  else if (p.min[1] < 0.6) shrubs.push([r2(x), r2(z), r2(w)])
}
const out = `// Generated by tools/garden.mjs from public/station/lair.glb: where the
// house's own garden plants stand. [x, z, top of the tree] and [x, z, width].
export const GARDEN = {
  trees: ${JSON.stringify(trees)},
  shrubs: ${JSON.stringify(shrubs)},
} as const
`
fs.writeFileSync(new URL('../src/station/garden.ts', import.meta.url), out)
console.log(`${parts.size} parts: ${trees.length} trees, ${shrubs.length} shrubs`)
